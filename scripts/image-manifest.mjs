// Writes src/content/image-manifest.ts: intrinsic size of every photo in public/images.
// <Photo> uses it to request a source wide enough for object-cover crops (no blur).
// Run after adding or replacing photos:  npm run images:manifest
import { imageSize } from "image-size";
import fs from "node:fs";
import path from "node:path";

const root = path.resolve("public");
const files = [];
(function walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full);
    else if (/\.(jpe?g|png|webp|avif)$/i.test(entry.name)) files.push(full);
  }
})(path.join(root, "images"));

const rows = files.sort().map((file) => {
  const { width, height } = imageSize(fs.readFileSync(file));
  return `  "/${path.relative(root, file).split(path.sep).join("/")}": [${width}, ${height}],`;
});

fs.writeFileSync(
  "src/content/image-manifest.ts",
  `// Generated by scripts/image-manifest.mjs — do not edit by hand.\nexport const imageManifest: Record<string, readonly [number, number]> = {\n${rows.join("\n")}\n};\n`,
);
console.log(`image manifest: ${rows.length} images`);
